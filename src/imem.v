module imem(pc, imem_o);
    input [31:0] pc;
    output wire [31:0] imem_o;

    reg [31:0] imem [0:1023]; // 32비트짜리 칸이 1024개(명령어 1024개 저장 가능)
    
    assign imem_o = imem[pc[11:2]]; //imem_o = pc+4라는 주소의 명령어

    initial begin
        /* R타입 검증
        imem[0] = 32'b0000000_00100_00000_000_00001_0010011;
        imem[1] = 32'b1111111_11110_00000_000_00010_0010011;
        imem[2] = 32'b0000000_00001_00010_000_00011_0110011;
        imem[3] = 32'b0100000_00001_00010_000_00100_0110011;
        imem[4] = 32'b0000000_00001_00010_111_00101_0110011;
        imem[5] = 32'b0000000_00001_00010_110_00110_0110011;
        */

        imem[0] = 32'b0000000_00000_00000_000_00001_0010011;
        imem[1] = 32'b0000000_00000_00000_000_00010_0010011;
        imem[2] = 32'b0000000_01010_00000_000_00011_0010011;
        imem[3] = 32'b0000000_00001_00001_000_00001_0010011;
        imem[4] = 32'b0000000_00001_00010_000_00010_0110011;
        imem[5] = 32'b1111111_00001_00011_001_11001_1100011;
    end
endmodule